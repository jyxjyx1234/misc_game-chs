        ori, trans = i.split("=")
        if ori in n:
            trans = n[ori]
        if "＆" in ori:
            oris = ori.split("＆")
            trans = []
            for _ in oris:
                if _ in n:
                    trans.append(n[_])
                else:
                    trans.append(_)
            trans = "＆".join(trans)
        for _ in range(len(replace1)):
            trans = trans.replace(replace1[_],replace2[_])
        f.write(ori + "=" + trans + "\n")
    

